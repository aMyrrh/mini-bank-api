CREATE TABLE transactions
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    type            VARCHAR(20)    NOT NULL,
    -- NULL for deposits: money comes from outside the bank
    from_account_id BIGINT,
    to_account_id   BIGINT         NOT NULL,
    amount          NUMERIC(19, 2) NOT NULL,
    category        VARCHAR(30),
    description     VARCHAR(255),
    created_at      TIMESTAMPTZ    NOT NULL DEFAULT now(),

    CONSTRAINT pk_transactions PRIMARY KEY (id),
    CONSTRAINT fk_transactions_from_account FOREIGN KEY (from_account_id) REFERENCES accounts (id),
    CONSTRAINT fk_transactions_to_account FOREIGN KEY (to_account_id) REFERENCES accounts (id),
    CONSTRAINT chk_transactions_type CHECK (type IN ('DEPOSIT', 'TRANSFER')),
    CONSTRAINT chk_transactions_amount_positive CHECK (amount > 0),
    CONSTRAINT chk_transactions_different_accounts CHECK (from_account_id <> to_account_id),
    CONSTRAINT chk_transactions_category CHECK (category IN
        ('GROCERIES', 'RESTAURANTS', 'TRANSPORT', 'UTILITIES',
         'HEALTH', 'ENTERTAINMENT', 'SHOPPING', 'OTHER'))
);

CREATE INDEX idx_transactions_from_account_id ON transactions (from_account_id);
CREATE INDEX idx_transactions_to_account_id ON transactions (to_account_id);
