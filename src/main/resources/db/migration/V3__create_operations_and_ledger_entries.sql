CREATE TABLE operations
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    type        VARCHAR(20)    NOT NULL,
    amount      NUMERIC(19, 2) NOT NULL,
    currency    VARCHAR(3)     NOT NULL,
    category    VARCHAR(30),
    description VARCHAR(255),
    created_at  TIMESTAMPTZ    NOT NULL DEFAULT now(),

    CONSTRAINT pk_operations PRIMARY KEY (id),
    CONSTRAINT chk_operations_type CHECK (type IN ('DEPOSIT', 'TRANSFER')),
    CONSTRAINT chk_operations_amount_positive CHECK (amount > 0),
    CONSTRAINT chk_operations_currency CHECK (currency IN ('RUB', 'USD', 'EUR')),
    CONSTRAINT chk_operations_category CHECK (category IN
        ('GROCERIES', 'RESTAURANTS', 'TRANSPORT', 'UTILITIES',
         'HEALTH', 'ENTERTAINMENT', 'SHOPPING', 'OTHER'))
);

-- One row per balance change: a transfer creates two entries, a deposit creates one
CREATE TABLE ledger_entries
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    operation_id  BIGINT         NOT NULL,
    account_id    BIGINT         NOT NULL,
    direction     VARCHAR(6)     NOT NULL,
    amount        NUMERIC(19, 2) NOT NULL,
    balance_after NUMERIC(19, 2) NOT NULL,
    created_at    TIMESTAMPTZ    NOT NULL DEFAULT now(),

    CONSTRAINT pk_ledger_entries PRIMARY KEY (id),
    CONSTRAINT fk_ledger_entries_operation FOREIGN KEY (operation_id) REFERENCES operations (id),
    CONSTRAINT fk_ledger_entries_account FOREIGN KEY (account_id) REFERENCES accounts (id),
    CONSTRAINT uk_ledger_entries_operation_account UNIQUE (operation_id, account_id),
    CONSTRAINT chk_ledger_entries_direction CHECK (direction IN ('DEBIT', 'CREDIT')),
    CONSTRAINT chk_ledger_entries_amount_positive CHECK (amount > 0),
    CONSTRAINT chk_ledger_entries_balance_after_non_negative CHECK (balance_after >= 0)
);

CREATE INDEX idx_ledger_entries_account_id ON ledger_entries (account_id);
